it("removes a read-only tree, and does nothing for a path that does not exist", () => {
  const top = join(tmp(), "export");
  mkdirSync(join(top, "snapshot/web/src"), { recursive: true });
  writeFileSync(join(top, "snapshot/web/src/orbit.ts"), "export {};\n");
  writeFileSync(join(top, "export.json"), "{}\n");
  chmodSync(join(top, "snapshot/web/src/orbit.ts"), 0o444);
  for (const dir of ["snapshot/web/src", "snapshot/web", "snapshot"]) {
    chmodSync(join(top, dir), 0o555);
  }
  chmodSync(join(top, "export.json"), 0o444);
  removeTree(top);
  expect(existsSync(top)).toBe(false);
  removeTree(top);
  removeTree(join(top, "nothing/here"));
});

it("removes a link without following it", () => {
  const outside = join(tmp(), "outside");
  mkdirSync(join(outside, "keep"), { recursive: true });
  writeFileSync(join(outside, "keep/star.txt"), "star\n");
  chmodSync(join(outside, "keep"), 0o555);
  const top = join(tmp(), "export");
  mkdirSync(top);
  symlinkSync(outside, join(top, "link"));
  removeTree(top);
  expect(existsSync(top)).toBe(false);
  expect(lstatSync(join(outside, "keep")).mode & 0o777).toBe(0o555);
  expect(existsSync(join(outside, "keep/star.txt"))).toBe(true);
  chmodSync(join(outside, "keep"), 0o755);
  rmSync(outside, { recursive: true });
});
