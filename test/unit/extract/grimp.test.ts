// The grimp driver's run against a stand-in Python: it records how it was run in its working
// directory, then plays the given part. What the real driver reads from a snapshot is pinned
// by test/oracle/drivers/grimp.test.ts.
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, expect, it } from "vitest";
import type { ExportManifest } from "../../../src/export/index.js";
import { removeTree } from "../../../src/export/index.js";
import type { ExtractContext } from "../../../src/extract/context.js";
import { grimpDriver } from "../../../src/extract/drivers/grimp.js";
import { comparePaths, type GitMode } from "../../../src/model/index.js";
import { DEFAULT_PROFILE, type Rules } from "../../../src/profile/index.js";

const made: string[] = [];
afterAll(() => {
  for (const dir of made.splice(0)) removeTree(dir);
});

const DRIVER = fileURLToPath(
  new URL("../../../python/hakutaku_grimp_driver.py", import.meta.url),
);

// The stand-in records its arguments, working directory, environment and input, and gives
// `out` and `EMPTY` to the part it plays.
const RECORD = [
  'const fs = require("node:fs");',
  "const argv = process.argv.slice(2);",
  'const input = JSON.parse(fs.readFileSync(argv[argv.length - 1], "utf8"));',
  'fs.writeFileSync("record.json", JSON.stringify({ argv, cwd: process.cwd(), env: process.env, input }));',
  "const out = (o) => process.stdout.write(JSON.stringify(o));",
  'const EMPTY = { grimp: "3.18", modules: [], imports: [], external: [], layerViolations: [], unreadable: [], warnings: [] };',
].join("\n");

interface Setup {
  files: Record<string, string>;
  modes?: Record<string, GitMode>;
  metadataOnly?: string[];
  roots: string[];
  singleFileModules?: string[];
  layers?: Rules["layers"];
  body?: string;
  python?: boolean;
}

function manifestOf(s: Setup): ExportManifest {
  const paths = Object.keys(s.files).sort(comparePaths);
  return {
    formatVersion: 1,
    id: "observatory",
    commit: "f".repeat(40),
    commitTime: 1767225600,
    ref: "main",
    hakutakuVersion: "0.0.0",
    files: paths.length,
    denied: 0,
    engineConfigsRemoved: [],
    symlinks: [],
    submodules: [],
    refused: [],
    metadataOnly: (s.metadataOnly ?? []).map((path) => ({
      path,
      reason: "generated" as const,
    })),
    tree: paths.map((path) => ({
      path,
      mode: s.modes?.[path] ?? "100644",
      blob: "0".repeat(40),
      bytes: Buffer.byteLength(s.files[path] ?? ""),
    })),
  };
}

function standIn(s: Setup): { ctx: ExtractContext; logged: string[] } {
  const root = mkdtempSync(join(tmpdir(), "hakutaku-grimp-unit-"));
  made.push(root);
  const exportDir = join(root, "export");
  const snapshotDir = join(exportDir, "snapshot");
  mkdirSync(snapshotDir, { recursive: true });
  for (const [path, text] of Object.entries(s.files)) {
    if (s.modes?.[path] === "120000") continue; // a link is never made on disk
    mkdirSync(dirname(join(snapshotDir, path)), { recursive: true });
    writeFileSync(join(snapshotDir, path), text);
  }
  const workDir = join(root, "work");
  mkdirSync(workDir);
  const python = join(root, "python3");
  writeFileSync(
    python,
    `#!${process.execPath}\n${RECORD}\n${s.body ?? "out(EMPTY);"}\n`,
    { mode: 0o755 },
  );
  const logged: string[] = [];
  const profile = structuredClone(DEFAULT_PROFILE);
  profile.python = {
    roots: s.roots,
    singleFileModules: s.singleFileModules ?? [],
  };
  return {
    ctx: {
      exportDir,
      snapshotDir,
      workDir,
      enginesDir: join(root, "engines"),
      detail: "quick",
      noSource: false,
      profile,
      rules: s.layers === undefined ? null : { schema: 1, layers: s.layers },
      manifest: manifestOf(s),
      pythonPath: s.python === false ? null : python,
      log: (line) => logged.push(line),
    },
    logged,
  };
}

const record = (ctx: ExtractContext) =>
  JSON.parse(readFileSync(join(ctx.workDir, "record.json"), "utf8"));

// A package under sim/src with a stub, a generated module and a loose module beside it, and a
// single-file module.
const SKY: Setup = {
  files: {
    "sim/src/observatory/__init__.py": "from . import a\n",
    "sim/src/observatory/a.py": "import json\n",
    "sim/src/observatory/a.pyi": "x: int\n",
    "sim/src/observatory/gen.py": "# Code generated by skygen. DO NOT EDIT.\n",
    "sim/src/observatory/sky map.py": "import os\n",
    "sim/src/observatory/ephemeris/__init__.py": "",
    "sim/src/observatory/ephemeris/cli.py": "from .. import a\n",
    "sim/src/json.py": "raise SystemExit\n",
    "tools/skyctl.py": "import observatory\n",
    "docs/sky.md": "# sky\n",
  },
  metadataOnly: ["sim/src/observatory/gen.py"],
  roots: ["sim/src"],
  singleFileModules: ["tools/skyctl.py"],
  layers: [
    {
      name: "sky-layers",
      severity: "error",
      containers: ["observatory"],
      layers: ["ephemeris", "a"],
    },
    {
      name: "flat",
      severity: "warn",
      layers: ["observatory.ephemeris", "observatory.a"],
    },
  ],
};

it("applies only with a Python and a package under the profile's roots", () => {
  const applies = (s: Setup) => grimpDriver.applies(standIn(s).ctx);
  expect(applies(SKY)).toBe(true);
  expect(applies({ ...SKY, python: false })).toBe(false);
  // a single-file module alone, and a package outside every root
  expect(
    applies({
      files: { "tools/skyctl.py": "", "sim/src/observatory/__init__.py": "" },
      roots: ["lib"],
      singleFileModules: ["tools/skyctl.py"],
    }),
  ).toBe(false);
  // a package __init__.py that the tree holds as a link
  expect(
    applies({
      files: { "sim/src/observatory/__init__.py": "x" },
      modes: { "sim/src/observatory/__init__.py": "120000" },
      roots: ["sim/src"],
    }),
  ).toBe(false);
  // a package whose name a module under an earlier root holds
  expect(
    applies({
      files: { "observatory.py": "", "sim/src/observatory/__init__.py": "" },
      roots: [".", "sim/src"],
    }),
  ).toBe(false);
  // packages whose names the standard library of some Python, or grimp, holds
  for (const name of ["email", "test", "telnetlib", "grimp"]) {
    expect(
      applies({
        files: { [`sim/src/${name}/__init__.py`]: "" },
        roots: ["sim/src"],
      }),
    ).toBe(false);
  }
});

it("runs the driver under python -I -S -B over the input it writes, in the work directory, with Python's environment", async () => {
  const { ctx, logged } = standIn(SKY);
  const facts = await grimpDriver.run(ctx);
  expect(facts).toStrictEqual({
    version: "3.18",
    modules: new Set(),
    imports: [],
    external: new Set(),
    layerViolations: [],
  });
  const run = record(ctx);
  const input = join(ctx.workDir, "grimp-input.json");
  expect(run.argv).toStrictEqual(["-I", "-S", "-B", DRIVER, input]);
  expect(run.cwd).toBe(realpathSync(ctx.workDir));
  expect(run.env).toStrictEqual({
    PATH: join(ctx.workDir, "bin"),
    HOME: join(ctx.workDir, "home"),
    LANG: "C.UTF-8",
    TMPDIR: join(ctx.workDir, "tmp"),
    PYTHONNOUSERSITE: "1",
    PYTHONDONTWRITEBYTECODE: "1",
  });
  const view = join(ctx.workDir, "grimp");
  expect(run.input).toStrictEqual({
    enginesPython: join(ctx.enginesDir, "python"),
    roots: [join(view, "roots", "0")],
    packages: ["observatory"],
    singleFileModules: [
      { module: "skyctl", file: join(view, "single", "skyctl.py") },
    ],
    layers: [
      {
        name: "sky-layers",
        severity: "error",
        containers: ["observatory"],
        layers: ["ephemeris", "a"],
      },
      {
        name: "flat",
        severity: "warn",
        containers: [],
        layers: ["observatory.ephemeris", "observatory.a"],
      },
    ],
  });
  expect(readFileSync(input, "utf8")).toBe(
    `${JSON.stringify(run.input, null, 2)}\n`,
  );
  expect(existsSync(join(ctx.workDir, "grimp.out.json"))).toBe(false);
  expect(logged).toStrictEqual([]);
});

it("links each module file of a chosen package into its view, with an empty stand-in for a metadata-only one", async () => {
  const { ctx } = standIn(SKY);
  // a view left by an earlier run is replaced whole
  const stale = join(
    ctx.workDir,
    "grimp",
    "roots",
    "0",
    "observatory",
    "old.py",
  );
  mkdirSync(dirname(stale), { recursive: true });
  writeFileSync(stale, "import sky\n");
  await grimpDriver.run(ctx);
  const root = join(ctx.workDir, "grimp", "roots", "0");
  const linked = (path: string, to: string) => {
    expect(lstatSync(join(root, path)).isSymbolicLink()).toBe(true);
    expect(readlinkSync(join(root, path))).toBe(join(ctx.snapshotDir, to));
  };
  linked("observatory/__init__.py", "sim/src/observatory/__init__.py");
  linked("observatory/a.py", "sim/src/observatory/a.py");
  linked(
    "observatory/ephemeris/__init__.py",
    "sim/src/observatory/ephemeris/__init__.py",
  );
  linked(
    "observatory/ephemeris/cli.py",
    "sim/src/observatory/ephemeris/cli.py",
  );
  const gen = lstatSync(join(root, "observatory", "gen.py"));
  expect(gen.isFile() && gen.size === 0).toBe(true);
  // no stub, no file the module index names nothing, no loose module, no old file
  for (const path of [
    "observatory/a.pyi",
    "observatory/sky map.py",
    "json.py",
    "observatory/old.py",
  ]) {
    expect(existsSync(join(root, path))).toBe(false);
  }
  const single = join(ctx.workDir, "grimp", "single", "skyctl.py");
  expect(readlinkSync(single)).toBe(join(ctx.snapshotDir, "tools/skyctl.py"));
  // a metadata-only single-file module is an empty stand-in too
  const other = standIn({ ...SKY, metadataOnly: ["tools/skyctl.py"] });
  await grimpDriver.run(other.ctx);
  const stand = lstatSync(
    join(other.ctx.workDir, "grimp", "single", "skyctl.py"),
  );
  expect(stand.isFile() && stand.size === 0).toBe(true);
});

it("leaves out a package whose name a module under an earlier root, the standard library or grimp holds, and says so", async () => {
  const { ctx, logged } = standIn({
    files: {
      "observatory.py": "",
      "tools/__init__.py": "",
      "tools/cli.py": "import observatory\n",
      "sim/src/observatory/__init__.py": "",
      "sim/src/observatory/a.py": "",
      "sim/src/email/__init__.py": "",
      // the standard library's claim comes first: reordering the roots would not help
      "email.py": "",
      "sim/src/grimp/__init__.py": "",
      "sim/src/telnetlib/__init__.py": "",
      "sim/src/test/__init__.py": "",
    },
    roots: [".", "sim/src"],
  });
  expect(grimpDriver.applies(ctx)).toBe(true);
  await grimpDriver.run(ctx);
  const view = join(ctx.workDir, "grimp", "roots");
  expect(record(ctx).input.roots).toStrictEqual([join(view, "0")]);
  expect(record(ctx).input.packages).toStrictEqual(["tools"]);
  expect(existsSync(join(view, "1"))).toBe(false);
  const left = (dir: string, why: string) =>
    `grimp: left out the package ${dir}: ${why}; hakutaku's resolver reads its imports`;
  expect(logged).toStrictEqual([
    left("sim/src/email", "the standard library holds the name email"),
    left("sim/src/grimp", "grimp itself holds the name grimp"),
    left(
      "sim/src/observatory",
      "observatory.py holds the name observatory under the profile's roots",
    ),
    left("sim/src/telnetlib", "the standard library holds the name telnetlib"),
    left("sim/src/test", "the standard library holds the name test"),
  ]);
});

it("keeps stand-ins and unreadable files out of the modules it returns, and passes the driver's warnings on", async () => {
  const { ctx, logged } = standIn({
    ...SKY,
    body: [
      "const view = input.roots[0];",
      "out({ ...EMPTY,",
      '  modules: ["observatory", "observatory.a", "observatory.ephemeris", "observatory.ephemeris.cli", "observatory.gen", "skyctl"],',
      '  imports: [{ importer: "observatory.a", imported: "json", line: 1 }, { importer: "skyctl", imported: "observatory", line: 1 }, { importer: "observatory.a", imported: "observatory.gen", line: 2 }],',
      '  external: ["json", "numpy", "observatory"],',
      '  unreadable: [{ file: view + "/observatory/ephemeris/cli.py", reason: "a syntax error at line 1" }],',
      '  warnings: ["did not check the layers contract flat: no layer is in the graph"],',
      "});",
    ].join("\n"),
  });
  const facts = await grimpDriver.run(ctx);
  expect([...facts.modules]).toStrictEqual([
    "observatory",
    "observatory.a",
    "observatory.ephemeris",
    "skyctl",
  ]);
  expect(facts.imports).toStrictEqual([
    { importer: "observatory.a", imported: "json", line: 1 },
    { importer: "observatory.a", imported: "observatory.gen", line: 2 },
    { importer: "skyctl", imported: "observatory", line: 1 },
  ]);
  // as grimp read them, though the module index also names sim/src/json.py json
  expect([...facts.external]).toStrictEqual(["json", "numpy", "observatory"]);
  expect(logged).toStrictEqual([
    "grimp: could not read sim/src/observatory/ephemeris/cli.py (a syntax error at line 1); hakutaku's resolver reads its imports",
    "grimp: did not check the layers contract flat: no layer is in the graph",
  ]);
});

it.each<[string, string, RegExp]>([
  [
    "the driver's message on stderr",
    'process.stderr.write("SourceSyntaxError: Syntax error in sky.py, line 2\\n"); process.exit(3);',
    /^grimp failed: exit code 3\nSourceSyntaxError: Syntax error in sky\.py, line 2$/,
  ],
  ["a bare exit code", "process.exit(3);", /^grimp failed: exit code 3$/],
  [
    "a signal",
    'process.kill(process.pid, "SIGKILL");',
    /^grimp failed: stopped by SIGKILL$/,
  ],
  [
    "output that is not JSON",
    'process.stdout.write("{");',
    /^grimp's output is not JSON \(.+\)$/,
  ],
  [
    "output not in its shape",
    "out({ ...EMPTY, grimp: 3 });",
    /^grimp's output is not in its JSON shape: grimp is not a string$/,
  ],
])("fails with %s, and deletes its output", async (_what, body, message) => {
  const { ctx } = standIn({ ...SKY, body });
  await expect(grimpDriver.run(ctx)).rejects.toThrow(message);
  expect(existsSync(join(ctx.workDir, "grimp.out.json"))).toBe(false);
});
