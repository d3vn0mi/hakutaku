const made: string[] = [];
afterAll(() => {
  for (const dir of made.splice(0)) removeTree(dir);
});

const tmp = (): string => {
  const dir = mkdtempSync(join(tmpdir(), "hakutaku-paths-"));
  made.push(dir);
  return dir;
};

// Control characters are built from their codes, so this file holds none raw.
const BEL = String.fromCharCode(7);
const TAB = String.fromCharCode(9);
const DEL = String.fromCharCode(0x7f);

it.each<[string, string | null]>([
  ["../x", "dotdot"],
  ["a/../b", "dotdot"],
  ["/etc/passwd", "absolute"],
  [`a${BEL}b`, "control-char"],
  [`a${DEL}b`, "control-char"],
  ["web/src/a.ts", null],
  ["a..b/c", null],
])("refuseReason(%j) is %s", (p, want) => expect(refuseReason(p)).toBe(want));

it.each<[string, string | null]>([
  ["web/..", "dotdot"],
  ["..", "dotdot"],
  ["/../x", "dotdot"],
  [`sky${TAB}map.ts`, "control-char"],
  ["/sky.ts", "absolute"],
  ["...", null],
  ["web/.../a.ts", null],
  [`sky${String.fromCharCode(0x85)}.ts`, null],
  [`caf${String.fromCharCode(0xfffd)}.ts`, null],
])(
  "refuseReason(%j) is %s: dotdot first, then absolute, then C0 and DEL only",
  (p, want) => expect(refuseReason(p)).toBe(want),
);

// A number is a file of that many bytes; a string is the text.
const bytesOf = (content: number | string): Uint8Array =>
  typeof content === "number"
    ? new Uint8Array(content).fill(0x78)
    : new TextEncoder().encode(content);

it.each<[string, number | string, string | null]>([
  ["big.js", 1_048_577, "size"],
  ["web/app.min.js", 10, "minified"],
  ["gen.ts", "// @generated\nx", "generated"],
  ["ok.ts", "x", null],
])("metadataOnlyReason(%s) is %s", (path, content, want) =>
  expect(metadataOnlyReason(path, bytesOf(content))).toBe(want),
);

// Lines of `width` characters joined by line feeds, `count` of them.
const lines = (count: number, width: number, char = "x"): string =>
  Array.from({ length: count }, () => char.repeat(width)).join("\n");
const WIDE = String.fromCharCode(0x6f22); // three bytes in UTF-8
const ASTRAL = String.fromCodePoint(0x1f30c); // four bytes in UTF-8, two UTF-16 units

it.each<[string, string, number | string, string | null]>([
  ["exactly 1,048,576 bytes", "sky.js", `${lines(1024, 1023)}\n`, null],
  ["a minified name, .min.mjs", "web/app.min.mjs", "x", "minified"],
  ["a minified name, .min.cjs", "web/app.min.cjs", "x", "minified"],
  ["a minified name, .min.css", "web/sky.min.css", "x", "minified"],
  ["a minified name, .map", "web/app.js.map", "x", "minified"],
  ["a name in another case", "web/app.MIN.JS", "x", null],
  ["a .map name inside a name", "web/map.ts", "x", null],
  [
    "a line of 5,001 in 10,001 bytes",
    "sky.js",
    `${lines(1, 5001)}\n${lines(1, 4999)}`,
    "minified",
  ],
  ["a line of 10,000 in exactly 10,000 bytes", "sky.js", lines(1, 10000), null],
  [
    "lines of exactly 5,000 in 20,004 bytes",
    "sky.js",
    `${lines(4, 5000)}\n`,
    null,
  ],
  ["5,001 three-byte characters", "sky.ts", lines(1, 5001, WIDE), "minified"],
  [
    "5,000 three-byte characters in 15,000 bytes",
    "sky.ts",
    lines(1, 5000, WIDE),
    null,
  ],
  [
    "2,600 four-byte characters, 5,200 UTF-16 units",
    "sky.ts",
    lines(1, 2600, ASTRAL),
    null,
  ],
  ["5,001 four-byte characters", "sky.ts", lines(1, 5001, ASTRAL), "minified"],
  [
    "DO NOT EDIT on line 5",
    "gen.go",
    "a\nb\nc\nd\n// DO NOT EDIT\n",
    "generated",
  ],
  ["DO NOT EDIT on line 6", "gen.go", "a\nb\nc\nd\ne\n// DO NOT EDIT\n", null],
  [
    "Code generated on line 1",
    "gen.go",
    "// Code generated by sky-gen.\npackage sky\n",
    "generated",
  ],
  ["@Generated in another case", "gen.ts", "// @Generated\n", null],
  [
    "a minified name before a generated mark",
    "gen.min.js",
    "// @generated\n",
    "minified",
  ],
  [
    "the size before a generated mark",
    "gen.ts",
    `// @generated\n${lines(1, 1_048_576)}`,
    "size",
  ],
])("metadataOnlyReason: %s", (_, path, content, want) =>
  expect(metadataOnlyReason(path, bytesOf(content))).toBe(want),
);

